package io.crums.util.collections;

import java.util.AbstractCollection;
import java.util.AbstractMap;
import java.util.AbstractSet;
import java.util.Collection;
import java.util.Collections;
import java.util.Iterator;
import java.util.Map;
import java.util.Objects;
import java.util.Set;
import java.util.function.Function;

/**
 * Map classes and utilities.
 */
public class Maps {
  
  
  /**
   * Returns a read-only view of the given map. Not designed for
   * later modifying the given underlying map.
   */
  public static <K,V> Map<K,V> asReadOnly(Map<K,V> map) {
    return map.isEmpty() ? Map.of() : Collections.unmodifiableMap(map);
  }
  
  
  /**
   * Returns a read-only view of the given map with its values converted using
   * the given function.
   * 
   * <h4>Performance Note</h4>
   * <p>
   * Do not use the returned {@code Map}'s {@linkplain Map#entrySet()} for
   * anything other than <em>iterating</em> over the entries; look-up methods
   * on the entry set are slow (linear).
   * </p>
   * 
   * @param <K> the key type
   * @param <U> the base value type
   * @param <V> the target value type
   * 
   * @param valueMapper
   * @return
   */
  public static <K,U,V> Map<K,V> mapValues(Map<K,U> base, Function<U,V> valueMapper) {
    return base.isEmpty() ? Map.of() : new MappedValue<>(base, valueMapper);
  }



  /**
   * Returns a lazy "lookup" view of a {@code Collection} (typically a
   * {@code List}) where each element has a distinguishing (unique) field such
   * as a number, string, or other identifier. Look-ups are linear: one
   * way to think of the returned object is as a lazy abstraction of a
   * for loop.
   * 
   * <h4>Uniqueness Contract Unenforced</h4>
   * <p>
   * No effort is made to enforce that the keys generated by the given
   * {@code keyFunction} are unique. In the present implementation, during a
   * look-up, the first key found in the collection wins. However, other parts
   * of the java collections API contracts will be severely broken. <em>If the
   * uniqueness is violated, undefined behavior ensues.</em>
   * </p>
   * 
   * <h4>Performance Note</h4>
   * <p>
   * This method is suitable for collections containing few or tens of elements.
   * <em>Do not use for larger data sets requiring frequent look-ups.</em>
   * </p>
   * 
   * @param <K>       key type (output)
   * @param <V>       value type (same ass {@code Collection} type)
   * @param values    bag of values with unique identifiers
   * @param keyFunc   maps a value to a <em>unique</em> key
   * 
   * @return a lazy map of the given {@code values}, keyed by {@code keyFunction}
   */
  public static <K, V> Map<K, V> toMapView(
      Collection<V> values, Function<V, K> keyFunc) {
    return toMapView(values, keyFunc, Function.identity());
  }


  /**
   * Returns a lazy "lookup" view of a {@code Collection} (typically a
   * {@code List}) where each element has a distinguishing (unique) field such
   * as a number, string, or other identifier. Look-ups are linear: one
   * way to think of the returned object is as a lazy abstraction of a
   * for loop.
   * 
   * <h4>Uniqueness Contract Unenforced</h4>
   * <p>
   * No effort is made to enforce that the keys generated by the given
   * {@code keyFunction} are unique. In the present implementation, during a
   * look-up, the first key found in the collection wins. However, other parts
   * of the java collections API contracts will be severely broken. <em>If the
   * uniqueness is violated, undefined behavior ensues.</em>
   * </p>
   * 
   * <h4>Performance Note</h4>
   * <p>
   * This method is suitable for collections containing few or tens of elements.
   * <em>Do not use for larger data sets requiring frequent look-ups.</em>
   * </p>
   * 
   * @param <T>       collection type
   * @param <K>       key type (output)
   * @param <V>       value type (output)
   * @param <V>       value type (same ass {@code Collection} type)
   * @param values    bag of values with unique identifiers
   * @param keyFunc   maps values in the collection to <em>unique</em> keys
   * @param valFunc   maps values in the collection to values in the map
   * 
   * @return a lazy map of the given {@code values}, keyed by {@code keyFunction}
   */
  public static <T, K, V> Map<K, V> toMapView(
      Collection<T> values, Function<T, K> keyFunc, Function<T, V> valFunc) {
    
    return new AbstractMap<K,V>() {
      @Override
      public Set<Entry<K, V>> entrySet() {
        return new AbstractSet<Map.Entry<K,V>>() {
          @Override
          public int size() { return values.size(); }
          @Override
          public Iterator<Entry<K, V>> iterator() {
            return Iterators.map(
                values.iterator(),
                 t -> Map.entry(keyFunc.apply(t), valFunc.apply(t)));
          }
        };
      }
    };
  }



  
  
  
  /**
   * A read-only view of a {@linkplain Map} whose values are converted to another type via
   * a mapping function. This is meant as a lightweight wrapper for typical {@code Map} operations,
   * <em>however, the {@linkplain #entrySet()} implementation, is particularly inefficient.</em>,
   * 
   * @param <K> the key type
   * @param <U> the base value type
   * @param <V> the target value type
   */
  public static class MappedValue<K, U, V> extends ReadOnlyMap<K, V> {
    
    private final Map<K, U> base;
    private final Function<U, V> valueMapper;
    
    
    /**
     * 
     * @param base          base map
     * @param valueMapper   value-mapping function.
     */
    public MappedValue(Map<K, U> base, Function<U, V> valueMapper) {
      this.base = Objects.requireNonNull(base, "null base");
      this.valueMapper = Objects.requireNonNull(valueMapper, "null valueMapper");
    }
    

    @Override
    public int size() {
      return base.size();
    }

    @Override
    public boolean isEmpty() {
      return base.isEmpty();
    }

    @Override
    public boolean containsKey(Object key) {
      return base.containsKey(key);
    }

    @Override
    public boolean containsValue(Object value) {
      return value != null && values().contains(value);
    }

    @Override
    public V get(Object key) {
      U baseVal = base.get(key);
      return baseVal == null ? null : valueMapper.apply(baseVal);
    }

    @Override
    public Set<K> keySet() {
      return base.keySet();
    }

    @Override
    public Collection<V> values() {
      return new AbstractCollection<>() {
        @Override
        public Iterator<V> iterator() {
          return Iterators.map(base.values().iterator(), valueMapper);
        }
        @Override
        public int size() {
          return base.size();
        }
      };
    }

    
    /**
     * Do not use unless you simply use the returned object to iterate over the
     * entire entry set. Looks ups in the returned set are super-inefficient (but correct).
     * 
     * @return read-only set
     */
    @Override
    public Set<Entry<K, V>> entrySet() {
      return new AbstractSet<Map.Entry<K,V>>() {
        @Override
        public Iterator<Entry<K, V>> iterator() {
          return Iterators.map(
              base.entrySet().iterator(),
              e -> Map.entry(e.getKey(), valueMapper.apply(e.getValue())));
        }
        @Override
        public int size() {
          return base.size();
        }
      };
    }
    
  }
  
  
  
  public static abstract class ReadOnlyMap<K, V> implements Map<K, V> {
    @Override
    public final V put(K key, V value) {
      throw new UnsupportedOperationException();
    }
    @Override
    public final V remove(Object key) {
      throw new UnsupportedOperationException();
    }
    @Override
    public final void putAll(Map<? extends K, ? extends V> m) {
      throw new UnsupportedOperationException();
    }
    @Override
    public final void clear() {
      throw new UnsupportedOperationException();
    }
    

    /**
     * {@inheritDoc}
     */
    @Override
    public boolean equals(Object o) {
      if (o == this)
        return true;
      if (!(o instanceof Map))
        return false;
      Map<?,?> other = (Map<?,?>) o;
      if (size() != other.size())
        return false;
      for (var entry : entrySet()) {
        if (!Objects.equals(entry.getValue(), other.get(entry.getKey())))
          return false;
      }
      return true;
    }
    
    /**
     * {@inheritDoc}
     */
    @Override
    public int hashCode() {
      return entrySet().hashCode();
    }
    
    
    
  }
  
  

  /**
   * A swappable {@linkplain Map} implementation base class.
   * Designed to be subclassed. The use case is when a {@code Map}
   * sub-type needs to be sometimes insertion-ordered, other times
   * not.
   */
  public static class DelegateMap<K, V> implements Map<K, V> {
    
    
    protected final Map<K, V> delegate;
    
    
    public DelegateMap(Map<K, V> delegate) {
      this.delegate = Objects.requireNonNull(delegate, "null delegate Map");
    }
    
    
    @Override
    public V put(K key, V value) {
      return delegate.put(key, value);
    }
    
    
    @Override
    public V get(Object key) {
      return delegate.get(key);
    }

    @Override
    public Set<Entry<K, V>> entrySet() {
      return delegate.entrySet();
    }


    @Override
    public int size() {
      return delegate.size();
    }


    @Override
    public boolean isEmpty() {
      return delegate.isEmpty();
    }


    @Override
    public boolean containsKey(Object key) {
      return delegate.containsKey(key);
    }


    @Override
    public boolean containsValue(Object value) {
      return delegate.containsValue(value);
    }


    @Override
    public V remove(Object key) {
      return delegate.remove(key);
    }


    @Override
    public void putAll(Map<? extends K, ? extends V> m) {
      delegate.putAll(m);
    }


    @Override
    public void clear() {
      delegate.clear();
    }


    @Override
    public Set<K> keySet() {
      return delegate.keySet();
    }


    @Override
    public Collection<V> values() {
      return delegate.values();
    }


    /**
     * <p>A rare case where we can (and should) also delegate this method.</p>
     * {@inheritDoc}
     */
    @Override
    public int hashCode() {
      return delegate.hashCode();
    }


    /**
     * <p>A rare case where we can (and should) also delegate this method.</p>
     * {@inheritDoc}
     */
    @Override
    public boolean equals(Object obj) {
      return delegate.equals(obj);
    }
    
  }
  
  
  
  
  
  
  

}
